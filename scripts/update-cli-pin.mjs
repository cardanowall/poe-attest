#!/usr/bin/env node
// Maintainer tool: regenerate src/pins.ts for a given cardanowall CLI release.
//
//   node scripts/update-cli-pin.mjs <version>   # e.g. 0.9.0
//
// It downloads that release's SHA256SUMS and all five platform archives,
// verifies each archive against the manifest, extracts each, hashes the
// contained binary, and writes the pins module. The manifest hashes archives
// only, so the action needs BOTH digests: the archive digest (checked before
// extraction) and the binary digest (checked before every spawn, including
// tool-cache hits on long-lived self-hosted runners).

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const TARGETS = [
  'x86_64-unknown-linux-musl',
  'aarch64-unknown-linux-musl',
  'x86_64-apple-darwin',
  'aarch64-apple-darwin',
  'x86_64-pc-windows-msvc',
];

function isWindows(target) {
  return target.includes('windows');
}
function archiveExtension(target) {
  return isWindows(target) ? 'zip' : 'tar.gz';
}
function archiveStem(version, target) {
  return `cardanowall-v${version}-${target}`;
}
function archiveName(version, target) {
  return `${archiveStem(version, target)}.${archiveExtension(target)}`;
}
function binaryName(target) {
  return isWindows(target) ? 'cardanowall.exe' : 'cardanowall';
}
function releaseBaseUrl(version) {
  return `https://github.com/cardanowall/label-309-cli/releases/download/v${version}`;
}

function sha256(buffer) {
  return createHash('sha256').update(buffer).digest('hex');
}

async function download(url) {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) {
    throw new Error(`download failed (${response.status} ${response.statusText}): ${url}`);
  }
  return Buffer.from(await response.arrayBuffer());
}

function parseSha256Sums(text) {
  const digests = new Map();
  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim();
    if (line === '' || line.startsWith('#')) continue;
    const match = /^([0-9a-fA-F]{64})\s+\*?(\S.*?)\s*$/.exec(line);
    if (match === null) continue;
    digests.set(match[2], match[1].toLowerCase());
  }
  return digests;
}

function extractBinary(archivePath, extractDir, version, target) {
  if (isWindows(target)) {
    execFileSync('unzip', ['-o', '-q', archivePath, '-d', extractDir], { stdio: 'inherit' });
  } else {
    execFileSync('tar', ['-xzf', archivePath, '-C', extractDir], { stdio: 'inherit' });
  }
  return join(extractDir, archiveStem(version, target), binaryName(target));
}

function renderPins(version, pins) {
  const rows = TARGETS.map((target) => {
    const { archiveSha256, binarySha256 } = pins[target];
    return (
      `  '${target}': {\n` +
      `    archiveSha256: '${archiveSha256}',\n` +
      `    binarySha256: '${binarySha256}',\n` +
      `  },`
    );
  }).join('\n');

  return `// AUTO-GENERATED by scripts/update-cli-pin.mjs, do not edit by hand.
// Pins the default cardanowall CLI release the action downloads. The release
// SHA256SUMS manifest hashes archives only, so this module records BOTH digests
// per target: the archive digest (verified before extraction) and the extracted
// binary digest (verified against the executable before every spawn).

import type { Target } from './platform';

export const DEFAULT_CLI_VERSION = '${version}';

export interface CliPin {
  /** SHA-256 of the release archive (\`.tar.gz\` / \`.zip\`). */
  archiveSha256: string;
  /** SHA-256 of the extracted \`cardanowall\` binary. */
  binarySha256: string;
}

export const CLI_PINS: Record<Target, CliPin> = {
${rows}
};
`;
}

async function main() {
  const version = process.argv[2];
  if (!version || !/^\d+\.\d+\.\d+/.test(version)) {
    console.error('usage: node scripts/update-cli-pin.mjs <version>   (e.g. 0.9.0)');
    process.exit(2);
  }

  const base = releaseBaseUrl(version);
  console.log(`Fetching SHA256SUMS for v${version} ...`);
  const sumsText = (await download(`${base}/SHA256SUMS`)).toString('utf8');
  const sums = parseSha256Sums(sumsText);

  const workDir = mkdtempSync(join(tmpdir(), 'cardanowall-pin-'));
  const pins = {};
  try {
    for (const target of TARGETS) {
      const name = archiveName(version, target);
      const expectedArchive = sums.get(name);
      if (!expectedArchive) {
        throw new Error(`SHA256SUMS has no entry for ${name}`);
      }
      console.log(`Downloading ${name} ...`);
      const archive = await download(`${base}/${name}`);
      const archiveSha256 = sha256(archive);
      if (archiveSha256 !== expectedArchive) {
        throw new Error(
          `${name}: archive SHA-256 mismatch, SHA256SUMS says ${expectedArchive}, got ${archiveSha256}`,
        );
      }
      const archivePath = join(workDir, name);
      writeFileSync(archivePath, archive);
      const binaryPath = extractBinary(archivePath, workDir, version, target);
      const binarySha256 = sha256(readFileSync(binaryPath));
      pins[target] = { archiveSha256, binarySha256 };
      console.log(`  archive  ${archiveSha256}`);
      console.log(`  binary   ${binarySha256}`);
    }
  } finally {
    rmSync(workDir, { recursive: true, force: true });
  }

  const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'pins.ts');
  writeFileSync(outPath, renderPins(version, pins));
  console.log(`\nWrote ${outPath}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
